-- CareFlow's additive schema. Hospital foundation tables remain managed by upstream JPA.
CREATE TABLE cf_inventory (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    name VARCHAR(160) NOT NULL, udi VARCHAR(80) NOT NULL, lot VARCHAR(80) NOT NULL,
    location VARCHAR(100) NOT NULL, category VARCHAR(80) NOT NULL, expires_on DATE NOT NULL,
    total_stock INTEGER NOT NULL, reserved_stock INTEGER NOT NULL DEFAULT 0,
    reorder_point INTEGER NOT NULL, quarantined BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT cf_unique_lot UNIQUE (udi, lot),
    CONSTRAINT cf_stock_bounds CHECK (total_stock >= 0 AND reserved_stock >= 0 AND reserved_stock <= total_stock AND reorder_point >= 0)
);
CREATE TABLE cf_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    item_id BIGINT NOT NULL REFERENCES cf_inventory(id), quantity INTEGER NOT NULL CHECK (quantity > 0),
    requested_by VARCHAR(100) NOT NULL, department VARCHAR(100) NOT NULL, purpose VARCHAR(500) NOT NULL,
    state VARCHAR(20) NOT NULL CHECK (state IN ('REQUESTED','APPROVED','RESERVED','FULFILLED','REJECTED','CANCELLED','EXPIRED')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL, updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    reserved_until TIMESTAMP WITH TIME ZONE
);
CREATE INDEX cf_request_owner ON cf_requests(requested_by);
CREATE INDEX cf_reservation_expiry ON cf_requests(state, reserved_until);
CREATE TABLE cf_fulfillments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key VARCHAR(100) NOT NULL UNIQUE,
    request_id BIGINT NOT NULL UNIQUE REFERENCES cf_requests(id), item_id BIGINT NOT NULL REFERENCES cf_inventory(id),
    quantity INTEGER NOT NULL CHECK (quantity > 0), fulfilled_by VARCHAR(100) NOT NULL,
    fulfilled_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE cf_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor VARCHAR(100) NOT NULL, action VARCHAR(40) NOT NULL, resource_type VARCHAR(20) NOT NULL,
    resource_id BIGINT NOT NULL, previous_state VARCHAR(100), new_state VARCHAR(100) NOT NULL,
    detail VARCHAR(500) NOT NULL, occurred_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX cf_audit_resource ON cf_audit(resource_type, resource_id);
