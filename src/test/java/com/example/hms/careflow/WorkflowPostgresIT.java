    @Test void upstreamRoleConstraintIsMigratedWithoutLosingExistingUsers() {
        var jdbc = new org.springframework.jdbc.core.JdbcTemplate(dataSource);
        String schema = "cf_upgrade_" + UUID.randomUUID().toString().replace("-", "");
        jdbc.execute("CREATE SCHEMA " + schema);
        try {
            jdbc.execute("CREATE TABLE " + schema + ".users (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username VARCHAR(255) NOT NULL UNIQUE, password VARCHAR(255) NOT NULL, role VARCHAR(255) NOT NULL CHECK (role IN ('ADMIN','DOCTOR','RECEPTIONIST')))");
            jdbc.update("INSERT INTO " + schema + ".users (username,password,role) VALUES ('legacy.admin','synthetic-password','ADMIN')");
            org.flywaydb.core.Flyway.configure().dataSource(dataSource).schemas(schema).defaultSchema(schema)
                .baselineOnMigrate(true).baselineVersion("0").load().migrate();
            jdbc.update("INSERT INTO " + schema + ".users (username,password,role) VALUES ('new.requester','synthetic-password','REQUESTER')");
            assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM " + schema + ".users", Integer.class)).isEqualTo(2);
            assertThat(jdbc.queryForObject("SELECT role FROM " + schema + ".users WHERE username='legacy.admin'", String.class)).isEqualTo("ADMIN");
        } finally {
            // Only this test's freshly created, uniquely named schema is removed.
            jdbc.execute("DROP SCHEMA " + schema + " CASCADE");
        }
    }
