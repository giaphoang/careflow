    @Test void CF06_oneThousandCompetingRequestsCannotOversellLastUnit() throws Exception {
        var i=item(1);List<Long> ids=new ArrayList<>();
        for(int n=0;n<1000;n++) ids.add(approved(i.id(),1).id());
        AtomicInteger winners=new AtomicInteger();long start=System.nanoTime();
        try(var pool=Executors.newFixedThreadPool(32)) {
            List<Future<?>> work=new ArrayList<>();
            for(Long id:ids) work.add(pool.submit(()->{try {service.reserve(manager,id);winners.incrementAndGet();}catch(WorkflowException expected){if(!expected.getMessage().contains("Insufficient"))throw expected;}}));
            for(var future:work) future.get(120,TimeUnit.SECONDS);
        }
        long millis=TimeUnit.NANOSECONDS.toMillis(System.nanoTime()-start);
        assertThat(winners.get()).isEqualTo(1);assertThat(persisted(i.id()).getAvailableStock()).isZero();
        assertThat(persisted(i.id()).getTotalStock()).isEqualTo(1);assertThat(persisted(i.id()).getReservedStock()).isEqualTo(1);
        assertThat(requests.findAll().stream().filter(r->r.getState()==RequestState.RESERVED)).hasSize(1);
        evidence("reservation",millis,"operations=1000, workers=32, accepted=1, rejected=999, available=0, reserved=1, total=1");
    }
    @Test void CF02_oneThousandConcurrentRetriesCreateOneFulfillment() throws Exception {
        var i=item(1);var r=reserved(i.id(),1);Set<Long> receipts=ConcurrentHashMap.newKeySet();long start=System.nanoTime();
        try(var pool=Executors.newFixedThreadPool(32)) {
            List<Future<?>> work=new ArrayList<>();
            for(int n=0;n<1000;n++)work.add(pool.submit(()->receipts.add(service.fulfill(manager,r.id(),"stress-retry-key").id())));
            for(var future:work)future.get(120,TimeUnit.SECONDS);
        }
        long millis=TimeUnit.NANOSECONDS.toMillis(System.nanoTime()-start);
        assertThat(receipts).hasSize(1);assertThat(fulfillments.count()).isEqualTo(1);assertThat(persisted(i.id()).getTotalStock()).isZero();assertThat(persisted(i.id()).getReservedStock()).isZero();
        assertThat(service.audit(owner,r.id(),org.springframework.data.domain.PageRequest.of(0,20)).getContent().stream().filter(a->a.getAction().equals("FULFILLED"))).hasSize(1);
        evidence("fulfillment",millis,"operations=1000, workers=32, receipts=1, duplicate_fulfillments=0, total=0, reserved=0");
    }
    private void evidence(String name,long millis,String values) throws Exception {
        Files.createDirectories(Path.of("target","benchmarks"));
        Files.writeString(Path.of("target","benchmarks",name+".txt"),"PostgreSQL concurrency workload\n"+values+"\nelapsed_ms="+millis+"\njava="+System.getProperty("java.version")+"\n");
        System.out.println("CAREFLOW_BENCHMARK "+name+" "+values+" elapsed_ms="+millis);
    }
